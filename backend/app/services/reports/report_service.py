"""
Report Generation Service (Stage 10)

Generates structured audit reports in various formats.
"""
import json
from datetime import datetime
from typing import Optional
from uuid import UUID

from app.schemas.audit import AuditDetailResponse, AuditSummaryResponse, ClaimResponse, EvidenceResponse
from app.db.models import Audit, Claim, Evidence, SourceDocument


class ReportService:
    """Service for generating audit reports in various formats."""

    def __init__(self):
        pass

    def generate_markdown_report(self, audit: Audit) -> str:
        """
        Generate a Markdown report for the audit.

        Args:
            audit: The audit with all relationships loaded

        Returns:
            Markdown formatted report string
        """
        lines = []

        # Header
        lines.append(f"# Second Opinion — Audit Report")
        lines.append("")
        lines.append(f"**Audit ID:** {audit.id}")
        lines.append(f"**Status:** {audit.status}")
        lines.append(f"**Created:** {audit.created_at.isoformat()}")
        if audit.completed_at:
            lines.append(f"**Completed:** {audit.completed_at.isoformat()}")
        lines.append(f"**Total Claims:** {audit.total_claims}")
        lines.append("")

        # Original Answer
        lines.append("## Submitted Answer")
        lines.append("")
        lines.append(audit.original_answer)
        lines.append("")

        # Source Documents
        lines.append("## Source Documents")
        lines.append("")
        for doc in audit.source_documents:
            lines.append(f"- **{doc.file_name}** ({doc.mime_type})")
            lines.append(f"  - Pages: {doc.page_count or 'N/A'}")
            lines.append(f"  - Processing: {doc.processing_status}")
        lines.append("")

        # Summary
        verdict_counts = {
            "SUPPORTED": 0,
            "CONTRADICTED": 0,
            "UNSUPPORTED": 0,
            "AMBIGUOUS": 0,
            "POTENTIALLY_UNSAFE": 0,
            "UNABLE_TO_ASSESS": 0,
        }
        for claim in audit.claims:
            if claim.verdict in verdict_counts:
                verdict_counts[claim.verdict] += 1

        lines.append("## Summary")
        lines.append("")
        lines.append(f"- **Total Claims:** {audit.total_claims}")
        for verdict, count in verdict_counts.items():
            if count > 0:
                lines.append(f"- **{verdict}:** {count}")
        lines.append("")

        # Claims
        lines.append("## Claim Details")
        lines.append("")

        for i, claim in enumerate(audit.claims, 1):
            lines.append(f"### Claim {i}: {claim.claim_text}")
            lines.append("")
            lines.append(f"**Verdict:** {claim.verdict}")
            lines.append("")
            lines.append(f"**Explanation:** {claim.explanation}")
            if claim.evidence_strength:
                lines.append(f"**Evidence Strength:** {claim.evidence_strength}")
            if claim.requires_review:
                lines.append("**⚠ Requires Human Review**")
            lines.append("")

            # Evidence
            if claim.evidence:
                lines.append("**Evidence:**")
                lines.append("")
                for ev in claim.evidence:
                    doc_name = ev.document.file_name if ev.document else "unknown"
                    lines.append(f"- **Source:** {doc_name}")
                    if ev.page_number is not None:
                        lines.append(f"  - Page: {ev.page_number}")
                    lines.append(f"  - Relationship: {ev.relationship_type}")
                    lines.append(f"  - Validated: {'✓' if ev.validated else '✗'}")
                    lines.append(f"  - Quote: \"{ev.passage_text}\"")
                    lines.append("")
            else:
                lines.append("*No evidence found for this claim.*")
                lines.append("")

            if claim.requires_review:
                lines.append(f"*Note: This claim was marked as requiring human review (reason: {claim.verdict if claim.verdict == 'UNABLE_TO_ASSESS' else 'non-checkable content'}).*")
                lines.append("")

        # Footer
        lines.append("---")
        lines.append(f"*Report generated by Second Opinion on {datetime.utcnow().isoformat()}*")
        lines.append("*Unsupported does not mean false. Evidence over confident wording.*")

        return "\n".join(lines)

    def generate_json_report(self, audit: Audit) -> dict:
        """
        Generate a JSON report for the audit.

        Args:
            audit: The audit with all relationships loaded

        Returns:
            Dictionary representing the JSON report
        """
        # Build verdict counts
        verdict_counts = {
            "SUPPORTED": 0,
            "CONTRADICTED": 0,
            "UNSUPPORTED": 0,
            "AMBIGUOUS": 0,
            "POTENTIALLY_UNSAFE": 0,
            "UNABLE_TO_ASSESS": 0,
        }
        for claim in audit.claims:
            if claim.verdict in verdict_counts:
                verdict_counts[claim.verdict] += 1

        # Build claims list
        claims_data = []
        for claim in audit.claims:
            evidence_list = []
            for ev in claim.evidence:
                doc_name = ev.document.file_name if ev.document else "unknown"
                evidence_list.append({
                    "document_id": str(ev.document_id) if ev.document_id else None,
                    "document_name": doc_name,
                    "page_number": ev.page_number,
                    "quote": ev.passage_text,
                    "relationship": ev.relationship_type,
                    "validated": ev.validated,
                })

            claims_data.append({
                "claim_id": str(claim.id),
                "claim_text": claim.claim_text,
                "verdict": claim.verdict,
                "explanation": claim.explanation,
                "evidence_strength": claim.evidence_strength,
                "evidence": evidence_list,
                "requires_review": claim.requires_review,
            })

        # Source documents
        source_docs = []
        for doc in audit.source_documents:
            source_docs.append({
                "document_id": str(doc.id),
                "file_name": doc.file_name,
                "mime_type": doc.mime_type,
                "page_count": doc.page_count,
                "processing_status": doc.processing_status,
            })

        return {
            "audit_id": str(audit.id),
            "status": audit.status,
            "original_answer": audit.original_answer,
            "title": audit.title,
            "total_claims": audit.total_claims,
            "created_at": audit.created_at.isoformat() if audit.created_at else None,
            "completed_at": audit.completed_at.isoformat() if audit.completed_at else None,
            "summary": verdict_counts,
            "source_documents": source_docs,
            "claims": claims_data,
        }

    def generate_report(self, audit: Audit, format: str = "markdown") -> str:
        """
        Generate a report in the specified format.

        Args:
            audit: The audit with all relationships loaded
            format: Output format ("markdown" or "json")

        Returns:
            Formatted report string
        """
        if format.lower() == "json":
            return json.dumps(self.generate_json_report(audit), indent=2, default=str)
        else:
            return self.generate_markdown_report(audit)


def create_report_service() -> ReportService:
    """Create a report service instance."""
    return ReportService()